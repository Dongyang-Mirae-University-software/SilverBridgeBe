    CONSTRAINT pk_game_results       PRIMARY KEY (id),
    CONSTRAINT fk_game_results_user  FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE,
    CONSTRAINT chk_game_results_type CHECK (game_type IN ('MATCHING', 'WORD_QUIZ', 'ADDITION', 'SUBTRACTION'))
);


-- =============================================
-- 9. admin_audit_logs (관리자 행동 감사 로그)
-- =============================================
CREATE TABLE admin_audit_logs (
    id         BIGINT        NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    admin_id   VARCHAR(36)   NOT NULL,                   -- 행동한 관리자 ID (탈퇴 시에도 이력 보존, FK 없음)
    action     VARCHAR(30)   NOT NULL,                   -- 행동 유형 (AdminAuditAction enum)
    target_id  VARCHAR(100)  NULL,                       -- 대상 ID (userId / connectionId / announcementId)
    detail     VARCHAR(500)  NULL,                       -- 변경 내용 요약
    created_at TIMESTAMPTZ   NOT NULL DEFAULT NOW(),

    CONSTRAINT pk_admin_audit_logs       PRIMARY KEY (id),
    CONSTRAINT chk_admin_audit_action    CHECK (action IN (
        'USER_STATUS_CHANGE', 'USER_ROLE_CHANGE', 'USER_FORCE_DELETE',
        'FORCE_CONNECT', 'FORCE_DISCONNECT',
        'ANNOUNCEMENT_CREATE', 'ANNOUNCEMENT_UPDATE', 'ANNOUNCEMENT_PUBLISH', 'ANNOUNCEMENT_DELETE'
    ))
);


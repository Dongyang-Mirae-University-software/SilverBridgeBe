package kr.silverbridge.main.domain.sos.entity;

/**
 * SOS 이력의 발생 경로 - 피보호자가 SOS 화면에서 무엇을 눌러 이력이 생겼는지.
 *
 * <p>모든 경로가 <b>이력을 남기고 보호자 알림도 동일하게 발송된다</b>. 구분하는 이유는 보호자 이력 화면에서
 * "긴급 SOS를 눌렀다"와 "나에게 전화를 걸었다"가 다르게 읽혀야 하기 때문이다 - 알림 발송 여부를 가르는
 * 값이 아니므로 {@code SosNotificationListener}·{@code NotificationDispatcher}가 이 값을 읽게 만들지 말 것
 * (SOS 동작 설정 2026-07-23, ACK 2026-07-30 규칙의 연장 - 필수 알림에 조건을 붙이지 않는다).</p>
 */
public enum SosTriggerType {

    /** 긴급 SOS 버튼 - 피보호자가 SOS 화면의 큰 버튼을 눌렀다. 값이 없을 때의 기본값이다. */
    SOS_BUTTON,

    /** 보호자에게 직접 전화 - 피보호자가 SOS 화면에서 보호자 카드를 골라 전화를 걸었다. */
    GUARDIAN_CALL,
    /**
     * 챗봇 119 - 챗봇이 응급·마음 위기 답과 함께 띄운 119 버튼을 피보호자가 눌렀다(2026-11-17).
     * 마음 위기 답에서도 119 버튼을 누르면 이 값이다(다쳤거나 당장 위험한 상황).
     */
    CHATBOT_119,

    /**
     * 챗봇 109 - 챗봇이 자살·자해 위기 답(AI {@code layout.crisis})과 함께 띄운 자살예방 상담전화 109 버튼으로
     * 앱 안 109 키패드를 열고 통화 버튼을 눌렀다(2026-11-20 사용자 결정). 실제 전화는 걸리지 않는다.
     * 2026-11-17에는 위기 종류를 보호자에게 드러내지 않으려고 {@link #CHATBOT_119} 하나로 묶었으나,
     * 보호자가 위기 상담 요청을 알아야 한다는 사용자 판단으로 나눴다 - 보호자 이력에 "챗봇 109"로 보인다.
     */
    CHATBOT_109
}

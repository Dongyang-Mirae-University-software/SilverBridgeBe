package kr.silverbridge.main.domain.sos.entity;

/**
 * 피보호자가 긴급 SOS 버튼을 눌렀을 때의 동작 방식(환경설정 &gt; SOS 동작 설정).
 *
 * <p><b>이 설정이 정하는 것은 "119 안내를 어느 시점에 어떻게 보여줄지"뿐이다.</b> 119 화면은 프론트가
 * 그리며 백엔드는 관여하지 않는다. 백엔드는 값을 계정에 보관·제공하기만 한다.</p>
 *
 * <p><b>119로 실제 전화를 걸지 않는다(2026-08-26 결정).</b> 프론트는 119가 입력된 <b>키패드 화면만</b>
 * 보여주고 발신은 하지 않는다 - 학생 프로젝트라 실제 신고가 나가면 안 되기 때문이다. 그래서 아래 값 이름의
 * {@code CALL_119}는 "119에 전화를 건다"는 뜻이 아니라 <b>"119 화면을 언제 띄우는가"</b>를 가리킨다.
 * 이름과 의미가 어긋나 있으니 이름만 보고 발신 로직을 넣지 말 것.</p>
 *
 * <p><b>보호자 알림은 어떤 값에서도 항상 발송된다.</b> SOS는 생명과 직결되므로
 * {@code NotificationType.WARD_SOS}가 사용자 설정을 무시하고 강제 발송하는 필수 알림이고,
 * 이 설정으로 끌 수 없다. {@code CALL_119}는 "보호자 알림 없이"라는 뜻이 아님에 주의한다.</p>
 *
 * <p>값 이름은 프론트가 쓰던 키({@code call119}, {@code call119AndNotify}, {@code notifyGuardianFirst})와
 * 1:1로 대응시켜 화면 라벨만 교체하면 되도록 했다.</p>
 */
public enum SosAction {

    /** 119 화면 바로 표시 - 버튼을 누르면 곧바로 119가 입력된 키패드를 보여준다(보호자 알림도 함께 발송). */
    CALL_119,

    /** 119 화면 + 보호자 알림 안내 - 119 키패드와 함께 "보호자에게도 알렸다"는 안내를 보여준다. */
    CALL_119_AND_NOTIFY,

    /** 보호자에게 먼저 알린 뒤 119 안내 - 알림 발송 완료 화면에서 119 키패드로 넘어가는 버튼을 안내한다. */
    NOTIFY_GUARDIAN_FIRST
}

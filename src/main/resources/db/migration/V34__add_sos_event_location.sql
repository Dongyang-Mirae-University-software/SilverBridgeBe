--
-- 백엔드는 위치를 추정하지 않는다 — SOS는 버튼 입력이라 서버가 알 수 있는 위치 정보가 없다.
-- 프론트가 아는 값(거주지 라벨·브라우저 위치 역지오코딩 결과 등)을 발생 요청에 담아 보내면 그대로 보관한다.
--
-- NULL 허용 = "위치 미상". 프론트가 아직 보내지 않는 동안(=현재)에는 전부 NULL이며,
-- 기존 이력 백필도 필요 없다. 화면에서는 위치 줄을 생략하면 된다.
--
-- 위치는 보관·표시 전용이다 — 알림 발송 대상·정책에 관여하지 않는다.

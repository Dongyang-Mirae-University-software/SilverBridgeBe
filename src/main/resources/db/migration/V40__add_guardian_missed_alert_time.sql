-- 미복용 요약 발송 시각을 보호자가 직접 선택 (2026-08-27)
--
-- V37까지는 발송 시각이 application.yaml의 전역 값(medication.reminder.missed-alert.alert-time,
-- 기본 21:00) 하나뿐이라 모든 보호자가 같은 시각에 받았다. 생활 패턴이 제각각이라
-- "우리 집은 저녁 7시에 확인한다"를 반영할 수 없었다.
--
-- ⚠️ 이 시각은 발송 시각이자 집계 상한이다 - 지정 시각까지 복용 시각이 지난 약만 센다.
--    아직 먹을 때가 아닌 약을 미복용으로 통보하면 매일 거짓 알림이 나가기 때문이다(불변 규칙 ⑧).
--    따라서 시각을 이르게 잡을수록 그날 요약에 포함되는 약이 줄어든다. 의도된 동작이다.

-- NULL = 미설정 → 전역 기본값을 따른다.
--
-- NOT NULL DEFAULT '21:00'으로 박지 않은 이유 - 그러면 기존 보호자 전원이 21:00에 고정돼
-- 나중에 서버 기본값을 바꿔도 아무도 따라오지 않는다. NULL로 두면 "정하지 않았다"와
-- "21:00을 골랐다"가 구분되고 백필도 필요 없다.
ALTER TABLE guardian_medication_setting
    ADD COLUMN missed_alert_time TIME NULL;
